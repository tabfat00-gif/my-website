-- BEXO — videos section
--
-- Creates the `videos` table used by videos.html (public) and admin.html (CRUD).
-- Mirrors the existing `articles` / `software` pattern:
--   - public (anon) may READ published rows only
--   - authenticated admins may insert / update / delete through is_admin()
--
-- Run once in: Supabase Dashboard -> SQL Editor -> paste -> Run.
-- This file is idempotent: running it twice is safe.

create table if not exists public.videos (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  title         text not null,
  description   text,
  video_type    text not null default 'youtube',
  video_url     text not null,
  thumbnail_url text,
  category      text,
  duration      text,
  is_published  boolean not null default false
);

comment on table public.videos is 'BEXO videos section: youtube / facebook / private / ai sources.';

alter table public.videos enable row level security;

-- Grants: the public key (anon role) may only read; writes need an admin session.
grant select on public.videos to anon, authenticated;
grant insert, update, delete on public.videos to authenticated;

-- Public: published rows only.
drop policy if exists "Public can view published videos" on public.videos;
create policy "Public can view published videos"
  on public.videos for select
  to anon, authenticated
  using (is_published = true);

-- Admin: full access, including unpublished rows.
drop policy if exists "Admins can view all videos" on public.videos;
create policy "Admins can view all videos"
  on public.videos for select
  to authenticated
  using (is_admin());

drop policy if exists "Admins can insert videos" on public.videos;
create policy "Admins can insert videos"
  on public.videos for insert
  to authenticated
  with check (is_admin());

drop policy if exists "Admins can update videos" on public.videos;
create policy "Admins can update videos"
  on public.videos for update
  to authenticated
  using (is_admin())
  with check (is_admin());

drop policy if exists "Admins can delete videos" on public.videos;
create policy "Admins can delete videos"
  on public.videos for delete
  to authenticated
  using (is_admin());
